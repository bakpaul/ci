#!python
"""Final job of CI_generate_regression_references (runs once, after every build job).

Opens one REF-PR per repository that received references, adds the new `[ci-depends-on ...]` entries to the
SOFA-PR description and posts the single summary comment.

Terminology: SOFA-PR (PR_NUMBER), DEP-PR (existing `ci-depends-on`), REF-PR (opened here).
Environment: GH_TOKEN, PR_NUMBER, CI_UPDATE_REF (JSON of ci_update_ref_setup.py), GITHUB_REPOSITORY, GITHUB_RUN_ID.
"""
import json
import os
import re
import sys

import requests

if not os.environ.get("GH_TOKEN") or not os.environ.get("PR_NUMBER"):
    print("Error: GH_TOKEN and PR_NUMBER are required.")
    sys.exit(1)
os.environ.setdefault("GITHUB_TOKEN", os.environ["GH_TOKEN"])

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import checkPRInfoBeforeBuild as pr_info  # noqa: E402  (reused: API_URL, HEADERS, publish_github_message)

API = "https://api.github.com"
PR_NUMBER = os.environ["PR_NUMBER"]


def api(method, path, **kwargs):
    return requests.request(method, f"{API}/{path}", headers=pr_info.HEADERS, **kwargs)


def failed_os_jobs():
    """Names of the jobs of this run that failed (one job per OS in the build workflows)."""
    repo, run_id = os.environ.get("GITHUB_REPOSITORY"), os.environ.get("GITHUB_RUN_ID")
    if not repo or not run_id:
        return []
    failed, page = [], 1
    while True:
        r = api("GET", f"repos/{repo}/actions/runs/{run_id}/jobs", params={"per_page": 100, "page": page})
        if r.status_code != 200:
            print(f"Could not list the jobs of the run: {r.status_code}")
            return failed
        jobs = r.json()["jobs"]
        failed += [j["name"] for j in jobs if j["conclusion"] == "failure"]
        if len(jobs) < 100:
            return failed
        page += 1


def commits_os(full_name, base, branch):
    """(number of commits ahead of base, OS names found in their message `<os> references from PR ...`)."""
    r = api("GET", f"repos/{full_name}/compare/{base}...{branch}")
    if r.status_code != 200:
        return 0, []
    data = r.json()
    oses = sorted({m.group(1) for c in data["commits"]
                   if (m := re.match(r"(\w+) references from PR ", c["commit"]["message"]))})
    return data["ahead_by"], oses


def open_ref_pr(repo, branch, scenes, oses):
    """Return (pr_html_url, None) or (None, failure reason)."""
    owner = repo["full_name"].split("/")[0]
    existing = api("GET", f"repos/{repo['full_name']}/pulls", params={"head": f"{owner}:{branch}", "state": "open"})
    if existing.status_code == 200 and existing.json():
        return existing.json()[0]["html_url"], None
    scene_lines = "\n".join(f"- `{s}`" for s in scenes)
    body = (f"References ({', '.join(oses)}) generated by the CI for SOFA-PR sofa-framework/sofa#{PR_NUMBER}.\n\n"
            f"Scenes:\n{scene_lines}\n")
    r = api("POST", f"repos/{repo['full_name']}/pulls", json={
        "title": f"[ci] Add references from SOFA PR {PR_NUMBER}", "head": branch, "base": repo["base_branch"], "body": body})
    if r.status_code == 201:
        return r.json()["html_url"], None
    return None, f"{r.status_code} {r.text[:200]}"


def append_depends_on(urls):
    """Add `[ci-depends-on url]` lines to the SOFA-PR description."""
    pr_data = pr_info.fetch_pr_data()
    body = pr_data.get("body") or ""
    lines = [f"[ci-depends-on {u}]" for u in urls if f"[ci-depends-on {u}]" not in body]
    if not lines:
        return
    new_body = body.rstrip("\r\n") + "\r\n" + "\r\n".join(lines) + "\r\n"
    r = api("PATCH", f"repos/sofa-framework/sofa/pulls/{PR_NUMBER}", json={"body": new_body})
    if r.status_code != 200:
        print(f"Failed to update the SOFA-PR description: {r.status_code} {r.text}")


def main():
    payload = json.loads(os.environ["CI_UPDATE_REF"])
    branch = payload["branch"]
    new_depends_on, other_ref_prs, skipped, nothing = [], [], [], []

    for repo in payload["repos"]:
        scenes = [s for key in repo["keys"] for s in payload["scenes"][key]]
        if repo["skipped"]:
            skipped.append(f"- `{repo['full_name']}` (branch `{repo['base_branch']}`): {repo['skipped']}")
            continue
        ahead, oses = commits_os(repo["full_name"], repo["base_branch"], branch)
        if ahead == 0:
            nothing.append(repo["full_name"])
            continue
        url, reason = open_ref_pr(repo, branch, scenes, oses)
        if url is None:
            skipped.append(f"- `{repo['full_name']}`: REF-PR could not be opened ({reason})")
        elif repo["kind"] == "sofa" or repo["dep_pr_url"]:
            other_ref_prs.append({"repo": repo["full_name"], "url": url, "target": repo["base_branch"],
                                  "oses": oses, "scenes": scenes})
        else:
            new_depends_on.append({"repo": repo["full_name"], "url": url, "oses": oses, "scenes": scenes})

    if new_depends_on:
        append_depends_on([e["url"] for e in new_depends_on])

    failed = failed_os_jobs()

    message = f"## Regression references generation (branch `{branch}`)\n"
    if new_depends_on:
        message += "\n### New `ci-depends-on` added to the description\n"
        for e in new_depends_on:
            message += f"- {e['repo']}: {e['url']} ({', '.join(e['oses'])})\n"
    if other_ref_prs:
        message += ("\n### Other REF-PRs opened\nThese must be **merged by you** into the targeted PR for the new "
                    "references to be taken into account.\n")
        for e in other_ref_prs:
            message += (f"- {e['repo']}: {e['url']} -> branch `{e['target']}`; OS: {', '.join(e['oses'])}; "
                        f"scenes: {', '.join('`' + s + '`' for s in e['scenes'])}\n")
    if skipped:
        message += "\n### Skipped (permission or API failure)\n" + "\n".join(skipped) + "\n"
    if nothing:
        message += "\n### No reference generated for\n" + "\n".join(f"- {r}" for r in nothing) + "\n"
    if failed:
        message += "\n### Failed jobs\n" + "\n".join(f"- {j}" for j in failed) + "\n"
    if not (new_depends_on or other_ref_prs or skipped or nothing or failed):
        message += "\nNothing to report.\n"

    pr_info.publish_github_message(message, PR_NUMBER)


if __name__ == "__main__":
    main()
